def lookup_assignment(qualifying_groups: set[str]) -> dict[int, str] | None:
    """Given 8 qualifying group letters, return {match_number: group_letter}.

    Uses FIFA's published Annex C table. Returns None if the combination
    is not found (should never happen for valid 8-group subsets of A-L).
    """
    key = "".join(sorted(qualifying_groups))
    val = _TABLE.get(key)
    if val is None:
        return None
    return {m: val[i] for i, m in enumerate(_SLOT_ORDER)}
